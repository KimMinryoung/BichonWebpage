function t(ko, en) {
    return { ko, en };
}

// koFeedback/enFeedback are optional per-choice feedback lines, authored in the
// same order as the choices; ordered() reorders them alongside so the stored
// arrays stay aligned with the stored choices (correct answer first).
function q(answer, koPrompt, enPrompt, koChoices, enChoices, koExplanation, enExplanation, koFeedback, enFeedback) {
    function ordered(items) {
        return [
            items[answer],
            ...items.filter((_, index) => index !== answer),
        ];
    }
    const question = {
        type: 'multiple_choice',
        points: 0,
        prompt: t(koPrompt, enPrompt),
        choices: { ko: ordered(koChoices), en: ordered(enChoices) },
        answer: 0,
        explanation: t(koExplanation, enExplanation),
    };
    if (koFeedback && enFeedback) {
        question.choiceFeedback = { ko: ordered(koFeedback), en: ordered(enFeedback) };
    }
    return question;
}

function lesson(ch, level, titleKo, titleEn, questions) {
    return {
        id: `state-revolution-ch${String(ch).padStart(2, '0')}-${level}`,
        level,
        title: t(titleKo, titleEn),
        questions: questions.map((item, index) => ({
            ...item,
            id: `q${index + 1}`,
            points: level === 'advanced' ? 3 : 2,
        })),
    };
}

function map(ko, en) {
    return {
        ko: ko.map(([title, text]) => ({ title, text })),
        en: en.map(([title, text]) => ({ title, text })),
    };
}

function brief(conceptKo, conceptEn, termKo, termEn, modernKo, modernEn, focusKo, focusEn) {
    function sections(concepts, term, modern, focus, labels) {
        return [
            { title: labels[0], items: concepts.map(([title, text]) => title + ': ' + text) },
            { title: labels[1], text: term },
            { title: labels[2], text: modern },
            { title: labels[3], text: focus },
        ];
    }
    return {
        ko: sections(conceptKo, termKo, modernKo, focusKo, ['핵심 개념 먼저', '용어 풀이', '현대 적용', '이 장의 초점']),
        en: sections(conceptEn, termEn, modernEn, focusEn, ['Core concepts first', 'Term guide', 'Modern application', 'Chapter focus']),
    };
}

// A typed concept diagram rendered above the brief: kind 'flow' takes
// { title, steps: [{ label, note }] }, kind 'contrast' takes
// { title, left: { heading, rows }, right: { heading, rows } } per language.
function diagram(kind, ko, en) {
    return { kind, ko, en };
}

function chapter(ch, titleKo, titleEn, summaryKo, summaryEn, focusKo, focusEn, conceptKo, conceptEn, termKo, termEn, modernKo, modernEn, basic, advanced, extras) {
    return {
        id: `state-revolution-ch${String(ch).padStart(2, '0')}`,
        volumeNumber: 1,
        chapterNumber: ch,
        title: t(titleKo, titleEn),
        sourceUrl: `https://www.marxists.org/archive/lenin/works/1917/staterev/ch${String(ch).padStart(2, '0')}.htm`,
        summary: t(summaryKo, summaryEn),
        learningFocus: t(focusKo, focusEn),
        conceptBrief: brief(conceptKo, conceptEn, termKo, termEn, modernKo, modernEn, focusKo, focusEn),
        conceptMap: map(conceptKo, conceptEn),
        lessons: [
            lesson(ch, 'basic', `${titleKo} 기본`, `${titleEn}: Basics`, basic),
            lesson(ch, 'advanced', `${titleKo} 심화`, `${titleEn}: Advanced`, advanced),
        ],
        ...(extras || {}),
    };
}

