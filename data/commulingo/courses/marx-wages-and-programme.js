// CommuLingo course: Marx's Value, Price and Profit (1865) and Critique of the
// Gotha Programme (1875) read as one book.
//
// The two belong together. In 1865 Marx tells the General Council of the
// International why wage struggle is possible against Citizen Weston, who had
// argued from a fixed fund that it is futile; in 1875 he tells the German party
// why a socialism built on distribution is a dead end. The first half answers
// 'can we win a rise?', the second 'is winning rises what socialism is?' — and
// both end on the same sentence, that the wages system itself is the object.
//
// Part 1 follows the fourteen sections of the 1865 address, compressed into
// four chapters; Part 2 follows the four parts of the 1875 marginal notes.
// Every sourceUrl points at the section the chapter is drawn from.
//
// The glossary carries the same material as reference entries — 임금기금설,
// 임금철칙, 맬서스주의, 노동전수익권, 공산주의의 낮은 단계와 높은 단계,
// 고타강령 비판 — so a reader who wants the encyclopaedia article rather than
// the lesson has somewhere to go.
//
// Chapter ids must stay stable: lesson ids are derived from them and progress
// is stored per lesson id.

function t(ko, en) {
    return { ko, en };
}

// Choices are authored with the correct answer at index `answer`; ordered()
// moves it to the front and the client shuffles on render, so the source stays
// readable while the stored answer is always 0. Mirrors the other course files.
function q(answer, koPrompt, enPrompt, koChoices, enChoices, koExplanation, enExplanation) {
    function ordered(choices) {
        return [choices[answer], ...choices.filter((_, index) => index !== answer)];
    }
    return {
        type: 'multiple_choice',
        points: 0,
        prompt: t(koPrompt, enPrompt),
        choices: { ko: ordered(koChoices), en: ordered(enChoices) },
        answer: 0,
        explanation: t(koExplanation, enExplanation),
    };
}

function lesson(ch, level, titleKo, titleEn, questions) {
    return {
        id: `wages-programme-ch${String(ch).padStart(2, '0')}-${level}`,
        level,
        title: t(titleKo, titleEn),
        questions: questions.map((item, index) => ({
            ...item,
            id: `q${index + 1}`,
            points: level === 'advanced' ? 3 : 2,
        })),
    };
}

function brief(spec) {
    function sections(concepts, term, modern, focus, labels) {
        return [
            { title: labels[0], items: concepts.map(([title, text]) => `${title}: ${text}`) },
            { title: labels[1], text: term },
            { title: labels[2], text: modern },
            { title: labels[3], text: focus },
        ];
    }
    return {
        ko: sections(spec.conceptKo, spec.termKo, spec.modernKo, spec.focusKo,
            ['핵심 개념 먼저', '용어 풀이', '현대 적용', '이 장의 초점']),
        en: sections(spec.conceptEn, spec.termEn, spec.modernEn, spec.focusEn,
            ['Core concepts first', 'Term guide', 'Modern application', 'Chapter focus']),
    };
}

function conceptMap(spec) {
    return {
        ko: spec.conceptKo.map(([title, text]) => ({ title, text })),
        en: spec.conceptEn.map(([title, text]) => ({ title, text })),
    };
}

// Sixteen positional arguments is how the older course files do this; one spec
// object per chapter keeps the two languages of each field next to each other,
// which is what actually goes wrong when these are edited by hand.
function chapter(spec) {
    return {
        id: `wages-programme-ch${String(spec.ch).padStart(2, '0')}`,
        volumeNumber: 0,
        chapterNumber: spec.ch,
        partNumber: spec.part,
        partTitle: t(spec.partKo, spec.partEn),
        title: t(spec.titleKo, spec.titleEn),
        sourceUrl: spec.sourceUrl,
        summary: t(spec.summaryKo, spec.summaryEn),
        learningFocus: t(spec.focusKo, spec.focusEn),
        conceptBrief: brief(spec),
        conceptMap: conceptMap(spec),
        lessons: [
            lesson(spec.ch, 'basic', `${spec.titleKo} 기본`, `${spec.titleEn}: Basics`, spec.basic),
            lesson(spec.ch, 'advanced', `${spec.titleKo} 심화`, `${spec.titleEn}: Advanced`, spec.advanced),
        ],
    };
}

