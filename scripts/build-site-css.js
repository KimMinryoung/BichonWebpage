// The legacy sheet stays authoritative (and serves old HTML). Public pages
// request only the core and relevant modules derived from it.
const fs = require('node:fs');
const path = require('node:path');
const postcss = require('postcss');
const cssDir = path.join(__dirname, '../public/css');
const moduleNames = ['core', 'home', 'lists', 'prose', 'chat', 'auth', 'admin', 'hub'];
function moduleFor(selector) {
    if (/\.(?:chat-|persona-select|session-(?:list|card)|header-actions)/.test(selector)) return 'chat';
    if (/\.(?:posts-table|action-group)/.test(selector)) return 'admin';
    if (/\.(?:form-group|login-(?:box|container)|auth-divider)/.test(selector)) return 'auth';
    if (/\.(?:home-(?:page|hero|description|card|section))/.test(selector)) return 'home';
    if (/\.(?:post-(?:content|body|summary)|report-body|commu-person-markdown|table-scroll)/.test(selector)) return 'prose';
    if (/\.(?:hub-(?:section|source-btn|tags|tag))/.test(selector)) return 'hub';
    if (/\.(?:post-(?:list|item|meta|excerpt)|report-(?:tab|panel)|commu-update-|commu-(?:dict-search|people-search|search-hl)|hub-(?:meta|source|author))/.test(selector)) return 'lists';
    return 'core';
}
function buildSiteCss() {
    const source = postcss.parse(fs.readFileSync(path.join(cssDir, 'style.css'), 'utf8'));
    return Object.fromEntries(moduleNames.map(name => {
        const root = source.clone();
        root.walkRules(rule => {
            if (rule.parent.type === 'atrule' && rule.parent.name === 'keyframes') return;
            const selectors = rule.selectors.filter(selector => moduleFor(selector) === name);
            if (selectors.length) rule.selector = selectors.join(',\n');
            else rule.remove();
        });
        root.walkAtRules(rule => {
            if (rule.name === 'font-face' && name !== 'core') rule.remove();
            else if (rule.name === 'keyframes' && name !== 'chat') rule.remove();
        });
        root.walkComments(comment => comment.remove());
        root.walkAtRules(rule => { if (rule.nodes && !rule.nodes.length) rule.remove(); });
        return [name, `/* Generated by scripts/build-site-css.js; edit style.css. */\n${root.toString().trim()}\n`];
    }));
}
if (require.main === module) {
    for (const [name, css] of Object.entries(buildSiteCss())) {
        const file = path.join(cssDir, `site-${name}.css`);
        if (process.argv.includes('--check')) {
            if (fs.readFileSync(file, 'utf8') !== css) throw Error('Run node scripts/build-site-css.js');
        } else fs.writeFileSync(file, css);
    }
}
module.exports = { buildSiteCss, moduleFor };
