// Derive the CommuLingo sheets from commulingo.css, the one authored file, in
// source order: the listing and home sheets, and the shared + per-feature
// sheets of the other pages. Pages no longer load commulingo.css itself.
const fs = require('node:fs');
const path = require('node:path');
const postcss = require('postcss');
const sourcePath = path.join(__dirname, '../public/css/commulingo.css');
const outputPath = path.join(__dirname, '../public/css/commulingo-lists.css');
const shared = /^(?:commulingo-(?:page|shell|home|hero|total|status|resume|book-groups|books)|commu-(?:sr-only|book-|resume-|updates|people-|person-|office-|lineage-|role-category-|flag(?:-|$)|fate|career-|dict-|search-|scene-chip|topic-link|doc-link|term-(?:group-head|chip|link)|event-(?:grid|card|meta|period|original|category|link)|terms-page|events-page|docs-page|hub-(?:head|section)|drill-promo)|pos-|is-hidden)/;
const detail = /^(?:commu-person-(?:detail|markdown|sections|section|activity|activities|event)|commulingo-hero--(?:graph|decision|book))/;
function listSelector(selector) {
    if (selector.trim() === '[class*="pos-"]') return true;
    const first = selector.match(/\.([\w-]+)/);
    return first && shared.test(first[1]) && !detail.test(first[1]);
}
const home = /^(?:commulingo-(?:page|shell|home|hero(?:--home|-main|-dict(?:-label)?)?$|book-groups|books|resume)|commu-(?:book-|resume-|updates|dict-(?:nav|tab)|drill-promo|course-preview)|is-hidden)/;
function homeSelector(selector) {
    const first = selector.match(/\.([\w-]+)/);
    return first && home.test(first[1]);
}
function buildListCss(kind = 'lists') {
    const root = postcss.parse(fs.readFileSync(sourcePath, 'utf8'));
    root.walkRules(rule => {
        if (rule.parent.type === 'atrule' && rule.parent.name === 'keyframes') return;
        // CSS rules here use commas only as selector separators (including
        // :has/:not arguments with single selectors).
        const selectors = rule.selectors.filter(kind === 'home' ? homeSelector : listSelector);
        if (selectors.length) rule.selector = selectors.join(',\n');
        else rule.remove();
    });
    root.walkAtRules(rule => {
        if (rule.name === 'keyframes' && (kind === 'home' || rule.params !== 'commu-skel-pulse')) rule.remove();
        else if (rule.nodes && !rule.nodes.some(node => node.type !== 'comment')) rule.remove();
    });
    root.walkComments(comment => comment.remove());
    return '/* Generated by scripts/build-commulingo-list-css.js; edit commulingo.css. */\n' + root.toString().trim() + '\n';
}
// The other pages: commulingo-core.css with every rule no single feature
// owns, and commulingo-<feature>.css with the rules whose selectors name a
// class only that feature's markup uses (scripts/commulingo-css-features.json).
// Such a selector can only match inside that feature, so a page without it
// loses nothing. The feature sheet loads after the core one; the computed
// styles of each page kind were compared against the single sheet when this
// split was introduced (2026-11-11).
const featureClasses = require('./commulingo-css-features.json');
const FEATURES = Object.keys(featureClasses);
const classFeature = new Map(FEATURES.flatMap(name => featureClasses[name].map(cls => [cls, name])));
function selectorFeature(selector) {
    const owners = new Set();
    for (const match of selector.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) {
        const owner = classFeature.get(match[1]);
        if (owner) owners.add(owner);
    }
    return owners.size === 1 ? [...owners][0] : null; // two features' classes in one selector: shared
}
function buildPageCss(kind = 'core') {
    const root = postcss.parse(fs.readFileSync(sourcePath, 'utf8'));
    const wanted = kind === 'core' ? null : kind;
    root.walkRules(rule => {
        if (rule.parent.type === 'atrule' && rule.parent.name === 'keyframes') return;
        const selectors = rule.selectors.filter(selector => selectorFeature(selector) === wanted);
        if (selectors.length) rule.selector = selectors.join(',\n');
        else rule.remove();
    });
    root.walkAtRules(rule => {
        // Animations stay in the core sheet, where every page has them.
        if (rule.name === 'keyframes' && kind !== 'core') rule.remove();
        else if (rule.nodes && !rule.nodes.some(node => node.type !== 'comment')) rule.remove();
    });
    root.walkComments(comment => comment.remove());
    return '/* Generated by scripts/build-commulingo-list-css.js; edit commulingo.css. */\n' + root.toString().trim() + '\n';
}
const PAGE_SHEETS = ['core', ...FEATURES];

function outputs() {
    const sheets = { lists: buildListCss('lists'), home: buildListCss('home') };
    for (const kind of PAGE_SHEETS) sheets[kind] = buildPageCss(kind);
    return sheets;
}
if (require.main === module) {
    for (const [kind, css] of Object.entries(outputs())) {
        const file = kind === 'lists' ? outputPath : path.join(__dirname, `../public/css/commulingo-${kind}.css`);
        if (process.argv.includes('--check')) {
            if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== css) throw new Error('Run node scripts/build-commulingo-list-css.js');
        } else fs.writeFileSync(file, css);
    }
}
module.exports = { buildListCss, buildPageCss, selectorFeature, PAGE_SHEETS };
