// Derive the public listing sheet from the full sheet in source order. Keeping
// commulingo.css authoritative preserves the cascade on detail/training pages.
const fs = require('node:fs');
const path = require('node:path');
const postcss = require('postcss');
const sourcePath = path.join(__dirname, '../public/css/commulingo.css');
const outputPath = path.join(__dirname, '../public/css/commulingo-lists.css');
const shared = /^(?:commulingo-(?:page|shell|home|hero|total|status|resume|book-groups|books)|commu-(?:sr-only|book-|resume-|updates|people-|person-|office-|lineage-|role-category-|flag(?:-|$)|fate|career-|dict-|search-|scene-chip|topic-link|doc-link|term-(?:group-head|chip|link)|event-(?:grid|card|meta|period|original|category|link)|terms-page|events-page|hub-(?:head|section)|drill-promo)|pos-|is-hidden)/;
const detail = /^(?:commu-person-(?:detail|markdown|sections|section|activity|activities|event)|commulingo-hero--(?:graph|decision))/;
function listSelector(selector) {
    if (selector.trim() === '[class*="pos-"]') return true;
    const first = selector.match(/\.([\w-]+)/);
    return first && shared.test(first[1]) && !detail.test(first[1]);
}
function buildListCss() {
    const root = postcss.parse(fs.readFileSync(sourcePath, 'utf8'));
    root.walkRules(rule => {
        if (rule.parent.type === 'atrule' && rule.parent.name === 'keyframes') return;
        // CSS rules here use commas only as selector separators (including
        // :has/:not arguments with single selectors).
        const selectors = rule.selectors.filter(listSelector);
        if (selectors.length) rule.selector = selectors.join(',\n');
        else rule.remove();
    });
    root.walkAtRules(rule => {
        if (rule.name === 'keyframes' && rule.params !== 'commu-skel-pulse') rule.remove();
        else if (rule.nodes && !rule.nodes.some(node => node.type !== 'comment')) rule.remove();
    });
    root.walkComments(comment => comment.remove());
    return '/* Generated by scripts/build-commulingo-list-css.js; edit commulingo.css. */\n' + root.toString().trim() + '\n';
}
if (require.main === module) {
    const css = buildListCss();
    if (process.argv.includes('--check')) {
        if (fs.readFileSync(outputPath, 'utf8') !== css) throw new Error('Run node scripts/build-commulingo-list-css.js');
    } else fs.writeFileSync(outputPath, css);
}
module.exports = { buildListCss };
