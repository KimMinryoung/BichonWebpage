-- Glossary categories by kind, plus a main-region facet.
--
-- The ten categories mixed two axes: what a term names (theory, factions,
-- repression) and where or when it belongs (korea, contemporary,
-- international). With no rule for which axis wins, the catch-alls grew: the
-- 348 "international movement" entries held battles, rockets, treaties, cults
-- and foreign parties; the 301 "party and state" entries held parties, coups
-- and propaganda frames (the 'two currents' theory of the Poznań rising).
--
-- Now the category answers only "what kind of thing is this" (12 kinds), and
-- commulingo_terms.region answers "where is its main arena" (8 regions, from
-- its own registry). The Korean shelf becomes the korea region; the
-- contemporary shelf is the chronological sort. Every entry was reclassified
-- by Jev (commulingo_term_classification) against the new criteria in
-- leninbot commulingo/classify.py; the 445 entries under 0.8 confidence on
-- either axis were then read and decided from their definitions.

CREATE TABLE IF NOT EXISTS commulingo_term_regions (
    id         text        NOT NULL PRIMARY KEY,
    sort_order integer     NOT NULL DEFAULT 0,
    label_ko   text        NOT NULL DEFAULT '',
    label_en   text        NOT NULL DEFAULT '',
    updated_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE commulingo_term_regions IS
    'Glossary main-region registry (second chip row), ordered like the category registry. Terms reference it by commulingo_terms.region (nullable foreign key: an entry without one shows only while no region chip is selected).';

