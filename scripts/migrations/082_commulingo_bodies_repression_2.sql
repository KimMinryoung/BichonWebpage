## Later reinterpretation

The emphasis of the concept moved after Stalin''s death. Under Khrushchev the extrajudicial sentencing bodies were abolished and criminal procedure was codified, so that socialist legality was reinterpreted toward the guarantee of procedural rights. The revisions of the criminal and criminal-procedure codes in 1958 and 1960 were the result.

During perestroika the concept expanded again and was offered as a ground for protecting individual rights against the state, and the expression law-governed state entered official discourse. The history of socialist legality can be read as the movement of one term, across periods, from a means of defending the state to a means of defending the individual.'
