The programme divided five hundred days into four stages and sequenced measures across them. Early stages would cut the budget deficit and begin converting state enterprises into joint-stock companies and selling small businesses; price liberalization would follow in phases; and the final stage would open external economic relations and introduce partial convertibility of the rouble.

