In September 1962 the Kharkov economist Yevsei Liberman published Plan, Profit, Premium in Pravda. His diagnosis was that the directive indicators imposed on enterprises were too numerous and mutually contradictory, so that an enterprise could not know what it was supposed to optimize.

The proposal had three parts. First, replace the many directive indicators with a single family of measures, profit and profitability. Second, let the enterprise draft its own detailed plan on the basis of its own capacity, with higher bodies confining themselves to approval and adjustment. Third, tie bonuses to improvement in the rate of profit rather than to fulfilment of the plan, removing the incentive to keep targets low.

## Points at issue

The proposal addressed the incentive problem of the planned economy directly. Under a practice of ratcheting targets up from the previous year''s performance it was rational for an enterprise to conceal capacity, and Liberman''s proposal was an attempt to remove that perverse incentive.

The debate ran for several years in Pravda and the economic journals. Academicians such as Nemchinov and Trapeznikov took part and treated mathematical planning methods and the problem of price formation alongside it. The case against held that making profit the indicator would let profitability rather than social need determine production, and that where prices are set centrally profit cannot reflect managerial performance. The second objection was in fact borne out as the limit of the reform that followed.

## Outcome

The debate was institutionalized in the Kosygin reform of 1965. The number of directive indicators was cut, sales and profit were introduced as principal measures, and enterprises were allowed to fund bonuses and investment from retained earnings. The reform is regarded as the most systematic of the Soviet economic reforms.

Its results were nonetheless limited. The price system was not reformed alongside it and supply remained allocated, so the profit indicator gave distorted signals, and after the Prague Spring of 1968 discussion of economic reform contracted politically. The Liberman debate is treated as the first open attempt to introduce market principles inside a planned economy and was drawn on in Hungary''s New Economic Mechanism and in Chinese reform debates.'
