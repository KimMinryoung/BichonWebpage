Change in the political sphere proved more decisive. After the Nineteenth Party Conference of 1988 elections with multiple candidates were introduced, and the elections to the Congress of People''s Deputies in 1989 allowed political forces outside the party apparatus to form openly. In 1990 the constitutional clause granting the party a monopoly of power was deleted.

