The first is the gap between investment and revenue: the capital committed to AI infrastructure, meaning chips, data centres, and power capacity, is large relative to the revenue AI services yet produce. The second is circularity in investment, where leading firms are entangled through equity and contracts so that one party''s spending is booked as another''s revenue and valuations support each other. The third is technical limitation, where hallucination in large language models and constraints on use in work requiring high reliability slow monetization.

## Institutional warnings

In late 2025 the International Monetary Fund and the Bank of England formally warned that a correction in AI-related asset prices could transmit cascading shocks through financial markets. The ground of the warning was concentration: with a small number of firms accounting for a large share of major indices, a correction in that sector spreads to whole indices and to pension assets.

Comparison with the dot-com bubble of the late 1990s is a recurring element of the debate. The similarity noted is the pattern in which expectations of a new technology are priced in detached from cash flow. The differences noted are that today''s leading firms are large enterprises with actual earnings and cash, and that much of the investment takes the form of physical plant.

## Political-economic questions

Independently of whether it is a bubble, the phase itself is an object of analysis. Investment in AI infrastructure requires power, water, and land on a large scale, so local cost burdens and emissions arise with it. Because capital-intensive investment does not greatly increase employment, the question connects to the discussion of jobless growth, and through the cyclical character of chip demand it connects to the semiconductor supercycle.

An analysis from the standpoint of the rate of profit is also offered. On that view AI investment is large-scale fixed capital investment that raises the organic composition of capital, so that success brings pressure on the rate of profit while failure ends in the destruction of value. This is the point at which the bubble argument yields different conclusions depending on whether it is treated as a question of asset prices or of the structure of accumulation.'
