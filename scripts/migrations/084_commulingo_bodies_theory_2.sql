## The twentieth century

In postwar Western Europe social democratic parties accumulated substantive reformist achievements through the construction of welfare states and full-employment policy. Argument in this period shifted from the abolition of capitalism to how far distribution and power relations could be altered within it.

The period after the 1980s reopened the question. As earlier gains were rolled back under liberalized capital movement and fiscal constraint, the reversibility of reform itself became the point at issue. What the critique of reformism addresses today is not the futility of reforms but the reversibility of reforms that leave the structural power of capital in place.'
