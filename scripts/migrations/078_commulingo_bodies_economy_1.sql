Collective farms existed in three forms: the TOZ, which pooled only the cultivation of land; the artel, which pooled land, principal equipment, and labour while leaving households a plot and some livestock; and the commune, which pooled domestic life as well. When full collectivization began in 1930 the intermediate form, the artel, was adopted as the standard, and the Model Charter published on 1 March 1930 with its revision at the Second Congress of Collective Farm Shock Workers in February 1935 fixed the legal framework.

The charter granted the collective farm perpetual free use of state land and regulated, by region, the size of the household plot and the number of animals a household could keep. This provision for household plots created the dual structure of Soviet agriculture that followed.

