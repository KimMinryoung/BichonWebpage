In Bolshevik policy language the kulak was defined as the top of a threefold division into poor, middle, and rich peasants. The difficulty lay in identification. Use of hired labour, leasing of land or equipment, and trading activity were offered as indicators, but in the rural conditions of the 1920s these were matters of degree rather than a clear boundary. The proportion of households the statistical agencies counted as kulak varied widely with the method of survey.

## Liquidation as a class

In December 1929 Stalin formalized the line of liquidating the kulaks as a class, and the Politburo decision of 30 January 1930 with the OGPU order No. 44/21 issued under it set out how. Kulaks were sorted into three categories: the first to be arrested as counter-revolutionary activists and sent to camps or shot, the second deported to remote regions, and the third resettled on inferior land within their own district.

The sorting was done against regional quotas. To fill the number assigned to a village, middle peasants and then poor peasants who opposed collectivization were included, and the derived label podkulachnik, meaning kulak henchman, licensed the expansion. At this point kulak had ceased to be an economic category and become a political brand.

