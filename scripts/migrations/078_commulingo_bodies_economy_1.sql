Formally the kolkhoz was a cooperative whose general meeting elected its chairman. In practice it was a subordinate unit of state planning. Sowing plans came down from above, the harvest went first to the state as compulsory deliveries, and procurement prices were fixed below the cost of production. Machine Tractor Stations held the equipment and were paid in kind for its use, functioning at the same time as instruments of political supervision in the countryside.

