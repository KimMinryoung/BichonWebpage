Community wealth building starts from the problem that wealth produced in a local economy does not stay there. When large retailers and outside firms transfer revenue out of the area and public procurement is awarded to non-local corporations, the local circulation of income is broken. From this diagnosis, placing the ownership and control of wealth locally becomes the policy objective.

The approach differs from attracting growth. Where development strategies based on inward investment and subsidies depend on the decisions of outside capital, this model starts from redeploying the institutions and assets a place already has.

## Components

Four instruments combine. First, shifting the procurement of anchor institutions: large purchasers fixed in place, such as universities, hospitals, and municipalities, create stable demand when they direct procurement to local suppliers. Second, living wage policy, which raises wage standards in the public sector and among contractors and so increases local spending. Third, fostering cooperatives and social enterprises, which places the ownership structure itself locally. Fourth, local banking and public financial institutions, so that credit circulates within the area.

