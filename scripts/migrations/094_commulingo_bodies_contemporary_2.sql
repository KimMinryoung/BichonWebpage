The current distinguishes itself from two others. One is Soviet-style productivism, a course that took the expansion of production as the index of socialism and reproduced environmental destruction. The other is market-based green capitalism, which holds that carbon pricing and technological innovation can resolve the crisis. Ecosocialism holds that both paths fail unless the structure of ownership and of decisions over production is changed.

