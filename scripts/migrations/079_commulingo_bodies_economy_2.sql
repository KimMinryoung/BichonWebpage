The system carried defects that were identified repeatedly. Because targets were ratcheted upward from the previous year''s performance, enterprises had an incentive to conceal capacity and keep targets low. Where output targets were set in gross quantities, quality and assortment were sacrificed, and where input allocations fell short, enterprises built informal supply networks of their own.

