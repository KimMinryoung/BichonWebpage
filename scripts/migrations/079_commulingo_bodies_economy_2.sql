## Becoming binding

With the adoption of the first Five-Year Plan in 1928 the teleological method won. The control figures changed in character from forecasts reflecting market conditions into assignments handed down, and failure to meet them was treated as a breach of plan discipline. The economists who had defended the genetic method were removed politically, and Groman and Bazarov were convicted in the Menshevik trial of 1931.

Thereafter the control figures were combined with the system of material balances to form the basic instrument of Soviet planning. Annual control figures were allocated by branch, each branch subdivided them into assignments for enterprises, and the enterprise received both an output target and an allocation of inputs.

