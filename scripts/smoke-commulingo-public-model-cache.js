const assert = require('node:assert/strict');
const { createPublicModelCache } = require('../utils/public-model-cache');
(async () => {
    let time = 0;
    const cache = createPublicModelCache({ now: () => time });
    let calls = 0;
    let resolve;
    const pending = () => { calls++; return new Promise(r => { resolve = r; }); };
    const first = cache.get('ko', pending);
    const coalesced = cache.get('ko', pending);
    await Promise.resolve();
    assert.equal(calls, 1);
    resolve('한국어');
    assert.equal(await first, '한국어');
    assert.equal(await coalesced, '한국어');
    assert.equal(await cache.get('en', () => 'English'), 'English');
    time = 59999;
    assert.equal(await cache.get('ko', () => { throw Error('unexpected read'); }), '한국어');
    time = 60000;
    assert.equal(await cache.get('ko', pending), '한국어');
    assert.equal(await cache.get('ko', pending), '한국어');
    assert.equal(calls, 2);
    resolve('갱신');
    await new Promise(r => setImmediate(r));
    assert.equal(await cache.get('ko', pending), '갱신');
    time = 120000;
    assert.equal(await cache.get('ko', () => { throw Error('offline'); }), '갱신');
    await new Promise(r => setImmediate(r));
    time = 299999;
    assert.equal(await cache.get('ko', () => { throw Error('offline'); }), '갱신');
    await new Promise(r => setImmediate(r));
    time = 300000; // 240s since the last successful read began.
    await assert.rejects(cache.get('ko', () => { throw Error('offline'); }), /offline/);
    assert.equal(await cache.get('ko', () => '복구'), '복구');
    assert.equal(await cache.get('en', () => 'New English'), 'New English');
    const cold = createPublicModelCache();
    await assert.rejects(cold.get('ko', () => { throw Error('cold failure'); }), /cold failure/);
    assert.equal(await cold.get('ko', () => []), (await cold.get('ko', () => 'unexpected')));
    console.log('public models: language isolation, freshness, single refresh, failure retention and hard expiry OK');
})().catch(error => { console.error(error); process.exitCode = 1; });
