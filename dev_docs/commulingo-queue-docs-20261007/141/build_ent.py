import re
D='dl/'
g=open(D+'g3962016.txt').read().split('\n')
s=next(i for i,l in enumerate(g) if l.startswith('Настоящий Закон в соответствии'))
e=next(i for i,l in enumerate(g) if l.startswith('Статья 15.'))
garant=[l.strip() for l in g[s:e] if l.strip()]
k=open(D+'kiev_ent.txt').read().split('\n')
ks=next(i for i,l in enumerate(k) if l.startswith('Статья 15.'))
kiev=[l for l in k[ks:] if l.strip()]
out=garant+kiev
def rep(old_start, new):
    global out
    idx=[i for i,l in enumerate(out) if l.startswith(old_start)]
    assert len(idx)==1,(old_start,idx)
    out[idx[0]]=new
rep('4. Предприятие имеет право самостоятельно осуществлять','4. Предприятию, обеспечивающему значительные поставки на экспорт продукции (работ, услуг), может быть предоставлено право непосредственного осуществления экспортно-импортных операций (включая рынки капиталистических и развивающихся стран) и создания для этих целей хозрасчетной внешнеторговой фирмы. Предприятия, не имеющие права самостоятельного выхода на внешний рынок, участвуют в определении наилучших условий экспорта своей продукции (работ, услуг) через внешнеторговые объединения своего или других министерств и ведомств.')
rep('создавать в установленном порядке межотраслевые производства','создавать в установленном порядке межотраслевые производства, вычислительные центры коллективного пользования, научные, проектные, конструкторские, ремонтные, строительные, торговые и другие совместные предприятия и объединения;')
i=[j for j,l in enumerate(out) if l.startswith('Совет Министров СССР вправе также вводить')]
assert len(i)==1; del out[i[0]]
kiev=None
out=[re.sub(r'(\w*о) - ([а-яё])',r'\1-\2', l) for l in out]
out=[re.sub(r'\s*\(с изм\. и доп\.[^)]*\)\s*$','',l) for l in out]
out=[l.replace(' - ',' — ') for l in out]
open('ent_assembled.txt','w').write('\n'.join(out)+'\n')
print(len(out), sum(len(l) for l in out))
# --- corrections against Заря Востока 2.VII.1987 ---
txt=open('ent_assembled.txt').read()
FIX=[('конкурентноспособную','конкурентоспособную'),('неиспользованного имущества','неиспользуемого имущества'),
('и комсомольской организации условия','и комсомольской организаций условия'),('самофининсирования','самофинансирования'),
('заключаемых хозяйственные договоров','заключаемых хозяйственных договоров'),('собственное подсобное хозяйство','собственное подсобное сельское хозяйство'),
('участие в строительство домов','участие в строительстве домов'),('непосредственно изготовителям или','непосредственно изготовителем или'),
('Предприятие водо-, электро-','Предприятия водо-, электро-'),(' .','.')]
for a,b in FIX:
    assert a in txt,a
    txt=txt.replace(a,b)
L=txt.split('\n')
L=[l for l in L if not l.startswith('Постановлением Верховного Совета СССР от 20 ноября 1989') and not l.startswith('-----') and '(абзац введен Законом' not in l]
open('ent_assembled.txt','w').write('\n'.join(L))
print('fixed',len(L))
